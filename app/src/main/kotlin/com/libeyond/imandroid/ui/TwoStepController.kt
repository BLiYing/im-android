package com.libeyond.imandroid.ui

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import com.libeyond.imandroid.R
import com.libeyond.imandroid.data.TwoStepErrorKind
import com.libeyond.imandroid.data.TwoStepRules
import com.libeyond.imandroid.data.TwoStepStep
import com.libeyond.imandroid.i18n.Str
import com.libeyond.imandroid.sdk.IMClient
import com.libeyond.imandroid.sdk.api.Proof
import com.libeyond.imandroid.sdk.api.TwoStepSetup
import com.libeyond.imandroid.sdk.api.TwoStepStatus
import com.libeyond.imandroid.sdk.http.ApiException
import com.libeyond.imandroid.sdk.logging.IMLog
import kotlinx.coroutines.launch

/**
 * 「隐私与安全 ▸ 两步验证」的状态与动作（Screen 纯展示，CODING_STYLE §7②）。
 *
 * 由 `PrivacySecurityHost` 持有（`remember`），跨「进页 / 返回隐私页 / 再进页」存活：
 * 请求全挂 `client.scope`，**请求途中返回再进来，结果（尤其是只有这一次明文的恢复码）不会丢**。
 * 身份证明（密码或短信验证码）在确认身份弹层里输（[proof]，PHONE_AUTH_DESIGN §7.2），成功 / 离开即清；
 * 密钥、恢复码只在内存，离开对应页即丢。
 * **日志里不写验证码、密钥、恢复码、ticket**。
 */
class TwoStepController(private val client: IMClient, sec: SecurityState) {
    private val log = IMLog.tag("IM.TwoStep")

    var step by mutableStateOf(TwoStepStep.Intro); private set
    /** 已取到的状态；null = 还没取到（或失败）。 */
    var status by mutableStateOf<TwoStepStatus?>(null); private set
    private var statusFailed by mutableStateOf(false)

    /** 确认身份弹层；Host 画它。 */
    val proof = ProofController.of(client, sec)
    var code by mutableStateOf(""); private set
    var recoveryMode by mutableStateOf(false); private set
    var error by mutableStateOf(""); private set
    /** 无身份证明的请求（绑定确认）在途；带证明的在 [proof] 里。 */
    private var running by mutableStateOf(false)
    val busy: Boolean get() = running || proof.busy
    var setup by mutableStateOf<TwoStepSetup?>(null); private set
    var codes by mutableStateOf<List<String>?>(null); private set
    var codesRegenerated by mutableStateOf(false); private set
    var saved by mutableStateOf(false)
    /** 上次离开恢复码页时没勾「已保存」：状态页提示建议重新生成。 */
    var unsaved by mutableStateOf(false); private set
    var confirmDisable by mutableStateOf(false)
    var leaveDialog by mutableStateOf(false)
    var toast by mutableStateOf<String?>(null)
    private var lastEnableAt = 0L

    /** 隐私页那一行的右值依据：未取到 = null（留空）；失败当关闭、不弹错。 */
    val rowEnabled: Boolean? get() = status?.enabled ?: if (statusFailed) false else null

    suspend fun refresh() {
        runCatchingCancellable { client.twoStep.status() }
            .onSuccess { status = it; statusFailed = false }
            .onFailure { if (status == null) statusFailed = true }
    }

    /** 进两步验证页：恢复码待保存时原地恢复；否则按状态进介绍 / 状态页。 */
    fun open() {
        if (codes == null && !busy) {
            step = if (status?.enabled == true) TwoStepStep.Status else TwoStepStep.Intro
            clearForm()
        }
    }

    /** 状态刷新回来后若在 Intro/Status 间走错了，纠正（不动用户已进入的流程页）。 */
    fun syncStepToStatus() {
        val on = status?.enabled ?: return
        if (on && step == TwoStepStep.Intro) step = TwoStepStep.Status
        if (!on && step == TwoStepStep.Status && !busy) step = TwoStepStep.Intro
    }

    private fun clearForm() { code = ""; recoveryMode = false; error = "" }
    fun onCode(v: String) { code = v; error = "" }
    fun toggleRecovery() { recoveryMode = !recoveryMode; code = ""; error = "" }

    fun goto(s: TwoStepStep) { clearForm(); step = s }

    /** 返回键：true = 已在内部处理；false = 应退出两步验证回隐私页。 */
    fun back(): Boolean {
        if (TwoStepRules.needsLeaveConfirm(step)) { leaveDialog = true; return true }
        val target = TwoStepRules.backTarget(step) ?: run { dropSecrets(); return false }
        dropSecrets()
        goto(target)
        return true
    }

    /** 离开流程页：密钥、输入、确认身份弹层（含保留的验证码）一起丢。 */
    private fun dropSecrets() { setup = null; clearForm(); proof.clear() }

    // —— 开启：确认身份 → 绑定 → 恢复码 ——
    /** 介绍页点「开启」：先弹确认身份弹层，证明通过才 setup。 */
    fun startSetup() {
        if (busy) return
        error = ""
        withProof("setup", { p -> client.twoStep.setup(p) }, onFail = { e ->
            if (TwoStepRules.kindOf(e.code) == TwoStepErrorKind.AlreadyEnabled) { reloadAfterStateMismatch(); true } else false
        }) { su ->
            // 请求途中用户已退回别处就不再把人拽进绑定页（密钥丢弃，服务端待确认密钥会超时）
            if (step == TwoStepStep.Intro) { setup = su; clearForm(); step = TwoStepStep.Bind }
        }
    }

    fun submitBind() {
        if (busy || !TwoStepRules.isTotpComplete(code)) return
        val c = code
        run("enable", onFail = { e ->
            if (TwoStepRules.kindOf(e.code) == TwoStepErrorKind.Expired) { setup = null; clearForm(); step = TwoStepStep.Intro; error = Str.s(R.string.twostep_error_expired); true } else false
        }) {
            val r = client.twoStep.enable(c)
            lastEnableAt = System.currentTimeMillis()
            status = TwoStepStatus(true, lastEnableAt, r.recoveryCodes.size)
            showCodes(r.recoveryCodes, regenerated = false)
            toast = Str.s(R.string.twostep_toast_enabled)
        }
    }

    private fun showCodes(list: List<String>, regenerated: Boolean) {
        setup = null; clearForm()
        codes = list; saved = false; codesRegenerated = regenerated; step = TwoStepStep.Codes
    }

    /** 「完成」（已勾选）或确认离开：丢掉明文恢复码，回状态页并刷新剩余数。 */
    fun finishCodes(leftUnsaved: Boolean) {
        unsaved = leftUnsaved
        codes = null; saved = false; leaveDialog = false
        goto(TwoStepStep.Status)
        client.scope.launch { refresh(); syncStepToStatus() }
    }

    // —— 管理：重新生成 / 关闭（动态码 / 恢复码 + 确认身份）——
    fun submitVerify() {
        if (busy || !TwoStepRules.canSubmitVerify(code, recoveryMode)) return
        if (step == TwoStepStep.Disable) { confirmDisable = true; return }
        val c = TwoStepRules.submitCode(code, recoveryMode)
        withProof("regen", { p -> client.twoStep.regenerate(p, c) }, onFail = ::onManageFail) { r ->
            status = status?.copy(recoveryRemaining = r.recoveryCodes.size)
            unsaved = false
            showCodes(r.recoveryCodes, regenerated = true)
            toast = Str.s(R.string.twostep_toast_regenerated)
        }
    }

    fun runDisable() {
        confirmDisable = false
        if (busy) return
        val c = TwoStepRules.submitCode(code, recoveryMode)
        withProof("disable", { p -> client.twoStep.disable(p, c) }, onFail = ::onManageFail) {
            status = TwoStepStatus(false); unsaved = false
            goto(TwoStepStep.Intro)
            toast = Str.s(R.string.twostep_toast_disabled)
        }
    }

    private fun onManageFail(e: ApiException): Boolean {
        if (TwoStepRules.kindOf(e.code) == TwoStepErrorKind.NotEnabled) { reloadAfterStateMismatch(); return true }
        return false
    }

    /** 本地状态与服务端对不上（别的端已开 / 已关）：重取后纠正页面。 */
    private fun reloadAfterStateMismatch() {
        client.scope.launch { refresh(); clearForm(); step = if (status?.enabled == true) TwoStepStep.Status else TwoStepStep.Intro }
    }

    /**
     * 统一的请求壳：忙态防重入、挂 `client.scope`、失败翻成红字。
     * [onFail] 返回 true 表示调用方已处理（不再显示通用红字）。
     */
    private fun run(what: String, onFail: (ApiException) -> Boolean, block: suspend () -> Unit) {
        running = true; error = ""
        client.scope.launch {
            try {
                block()
                log.i("two_step_$what" + "_ok")
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Throwable) {
                pageError(what, e, onFail)
            } finally {
                running = false
            }
        }
    }

    /** 带身份证明的请求：证明本身错了（密码 / 短信验证码）留在弹层里重输；其余收起弹层、红字在页面上（如动态码不对）。 */
    private fun <T> withProof(what: String, call: suspend (Proof) -> T, onFail: (ApiException) -> Boolean, onOk: (T) -> Unit) {
        if (busy) return
        proof.submit(call, onOk = { log.i("two_step_$what" + "_ok"); onOk(it) }, onPageError = { pageError(what, it, onFail) })
    }

    private fun pageError(what: String, e: Throwable, onFail: (ApiException) -> Boolean) {
        log.w("two_step_$what" + "_failed", "err" to e.javaClass.simpleName, "code" to ((e as? ApiException)?.code ?: 0))
        if (e !is ApiException || !onFail(e)) error = messageFor(e)
    }

    private fun messageFor(e: Throwable): String {
        val api = e as? ApiException
        val kind = api?.let { TwoStepRules.kindOf(it.code) }
        val base = kind?.let { TwoStepRules.message(it) } ?: e.userMessage(Str.s(R.string.net_error_unreachable))
        // 刚用这个码开启过，马上又拿它做验证：同一时间步的码只能用一次
        val recent = System.currentTimeMillis() - lastEnableAt < RECENT_ENABLE_MS
        return if (kind == TwoStepErrorKind.CodeInvalid && recent && step != TwoStepStep.Bind) base + "\n" + TwoStepRules.waitNextHint() else base
    }

    private companion object { const val RECENT_ENABLE_MS = 90_000L }
}
